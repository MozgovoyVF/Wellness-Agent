// Агент-ревьюер: выносит вердикт по плану. Разбор ответа и ретрай — в харнессе,
// текст промпта — в prompts/, его версию выбирает харнесс.
//
// Тулов у ревьюера нет и быть не должно. Он — контур безопасности, и его единственный
// результат обязан быть вердиктом: агент, который может писать файлы, способен оставить
// след от плана, который сам же завернул. Всё, что ему нужно для решения — профиль,
// дневник и текст плана, — харнесс кладёт ему в контекст готовым. Появится соблазн дать
// ему getProfile «чтобы не дублировать чтение» — это тот же соблазн: тул-вызов у ревьюера
// открывает дверь остальным. Читает харнесс, ревьюер только судит.

import { Agent } from '@openai/agents';

const MODEL = process.env.DEEPSEEK_MODEL || 'deepseek-v4-flash';

export function createReviewer(instructions: string) {
  return new Agent({
    name: 'Safety Reviewer',
    instructions,
    model: MODEL,
  });
}
