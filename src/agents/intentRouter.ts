// Агент-классификатор: по тексту задачи называет модуль и свою уверенность. Оркестрация
// живёт не здесь, а в src/os/router.ts; текст промпта тоже не здесь — его загружает
// вызывающий, как и у остальных трёх агентов.
//
// Тулов у него нет, и это не экономия. Роутер обязан отдать одну строку и ничего больше:
// агент, способный читать профиль или писать файлы, найдёт чем заняться вместо
// классификации, а стоить это будет дороже самого прогона. Та же логика, что у триажа
// и ревьюера, — только там причина в безопасности, а здесь в цене и предсказуемости.

import { Agent } from '@openai/agents';

/**
 * Модель роутера. Отдельная переменная с откатом на основную: классификация — это один
 * короткий ответ, и платить за неё столько же, сколько за план, незачем. Нет
 * ROUTER_MODEL — работаем на той же модели, что и всё остальное.
 *
 * Читается ВНУТРИ функции, а не на уровне модуля: в скриптах .env грузится телом первого
 * импорта, и константа уровня модуля рискует взять дефолт. Ровно та же причина, по которой
 * модель читается внутри функции в traceRun.ts.
 */
function routerModel(): string {
  return process.env.ROUTER_MODEL || process.env.DEEPSEEK_MODEL || 'deepseek-v4-flash';
}

export function createRouter(instructions: string) {
  return new Agent({
    name: 'Intent Router',
    instructions,
    model: routerModel(),
  });
}
