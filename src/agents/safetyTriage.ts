// Агент триажа: смотрит на задачу до того, как её увидит коуч, и отвечает на один
// вопрос — это работа для wellness-коуча или для живого специалиста.
//
// Отдельный агент, а не режим ревьюера, потому что вопрос у него другой. Ревьюер судит
// план и неизбежно судит его качество: план, который грамотно отправляет человека к врачу,
// он видит как хороший план — так и был пропущен запрос про дозировки при болях в груди
// (runs/run-2026-08-17T08-38-34-265Z.json). Триаж плана не видит вовсе, и обелить перед
// ним запрос нечем.
//
// Тулов нет и быть не должно — по той же причине, что и у ревьюера (src/agents/safetyReviewer.ts):
// он контур безопасности, его единственный результат обязан быть ответом, а не следом на диске.

import { Agent } from '@openai/agents';

const MODEL = process.env.DEEPSEEK_MODEL || 'deepseek-v4-flash';

export function createTriage(instructions: string) {
  return new Agent({
    name: 'Safety Triage',
    instructions,
    model: MODEL,
  });
}
