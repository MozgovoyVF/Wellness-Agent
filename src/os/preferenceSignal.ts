// Явный сигнал «запиши это себе»: человек сам сказал «запомни» или «понравилось».
//
// Список маркеров в коде, а не решение модели, — по той же причине, по которой день
// недели считает calendarBlock(), а гейт живёт замыканием: политика записи в долгую
// память не должна зависеть от того, как модель поняла фразу. Ложное срабатывание
// кладёт в постоянную память случайную фразу, и стоит оно дороже, чем промах.
//
// Морфологии здесь нет и не будет — то же осознанное ограничение, что у nameBefore
// в src/skills/shopping.ts. «Имей в виду на будущее» поймается, «учитывай впредь» — нет.
// Цена промаха мала: предпочтение просто не запишется.

/**
 * Маркеры сигнала. Сравниваются по вхождению в приведённую к нижнему регистру задачу,
 * поэтому основы даны без окончаний: «мне понравил» ловит и «понравился», и «понравилось».
 */
const MARKERS = [
  'запомни',
  'запомните',
  'мне понравил',
  'понравилось',
  'больше так',
  'всегда так',
  'на будущее',
  'учти',
  'имей в виду',
];

/**
 * Фраза человека, если в ней есть явный сигнал, иначе null.
 *
 * Возвращается задача ДОСЛОВНО, а не пересказ: модель здесь не участвует вовсе — в этом
 * весь смысл выбора «ключевые слова в коде». Урезает вызывающий: длина записи — это его
 * решение, а не свойство сигнала.
 */
export function preferenceSignal(task: string): string | null {
  const haystack = task.toLowerCase();
  return MARKERS.some((marker) => haystack.includes(marker)) ? task.trim() : null;
}
