// Что такое модуль OS. Отдельный файл, потому что тип нужен и самим модулям, и реестру:
// импорт типа из index.ts, который эти модули собирает, замкнул бы цикл.
//
// ГЛАВНОЕ: модуль — это КОНФИГУРАЦИЯ, а не агент. Соблазн сделать восемь агентов
// и раздавать между ними задачу велик, и он же — ошибка, которой здесь нет: handoffs
// и подагенты завели бы восемь наборов промптов, восемь мест, где может разъехаться
// формат плана, и восемь дорог мимо ревьюера. Агент остаётся один — createCoach, —
// а модуль меняет два его аргумента из трёх.

import { MCP_TOOLS } from '../../mcp/toolNames';

export type Module = {
  /** Имя модуля. Оно же едет в трейс, в таймлайн и в expect.module у evals. */
  name: string;
  /**
   * Одна строка для роутера. Это ВХОД МОДЕЛИ, а не комментарий: из этих строк собирается
   * промпт классификатора. Правишь описание — правишь маршрутизацию, и заметят это evals,
   * а не человек.
   */
  description: string;
  /** Файл наслойки в prompts/modules/. null — наслойки нет, идёт голый промпт коуча. */
  promptFile: string | null;
  /**
   * Какие тулы видит коуч. null — все, что и так разрешены конфигом серверов.
   *
   * Сужение, а не расширение: список пересекается с политикой servers.config.ts, а не
   * заменяет её, — дать тул, которого там нет, модулем нельзя. Тулы записи сюда
   * не вписываются вовсе: ими командует только гейт (см. buildToolFilter).
   */
  tools: string[] | null;
};

/**
 * Тулы, которые есть у каждого специализированного модуля. Без профиля план нарушит
 * ограничение вслепую, без дневника обопрётся на выдумку — эти два нужны всегда,
 * какой бы ни была тема.
 */
export const ALWAYS: string[] = [MCP_TOOLS.readProfile, MCP_TOOLS.readRecentLogs];
