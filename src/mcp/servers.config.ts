// Реестр MCP-серверов прогона. Единственный файл, который правят, добавляя сервер:
// харнесс читает этот массив и поднимает всё, что включено, — про конкретные серверы
// он не знает ничего, ни сколько их, ни какие.
//
// В этом весь предмет урока. Свой markdown-health мы написали сами, а filesystem, weather
// и notion взяли готовыми из npm: интеграция с ними — это запись здесь, а не код.
// Обёрток над их тулами нет и быть не должно: агент получает чужие тулы как есть, с их
// собственными именами и схемами, и в трейсе они стоят наравне с нашими.
//
// Раньше эту работу делал src/mcp/healthMcp.ts — модуль на один сервер, где имя, команда
// и фильтр тулов были зашиты в код. Его больше нет: держать первый сервер по-старому,
// а остальные три по-новому значило бы, что тезис «добавить сервер = запись в конфиге»
// неверен для первого же сервера.

import { join } from 'node:path';
import { MCP_TOOLS, NOTION_TOOLS } from './toolNames';

// cwd, а не import.meta.url: после сборки этот модуль лежит внутри .next/. По той же
// причине cwd явно передаётся дочернему процессу — data/ он ищет от рабочей директории.
const ROOT = process.cwd();

// Наш сервер написан на TypeScript, а запускается как обычный процесс, поэтому нужен tsx.
// Путь до его cli, а не строка «npx tsx»: npx каждый раз заново решает, что запускать.
// Внешние серверы этой оптимизации не получают — их как раз и надо достать из сети, —
// но качать нечего только у своего, и разница здесь именно в этом, а не в небрежности.
const TSX_CLI = join(ROOT, 'node_modules', 'tsx', 'dist', 'cli.mjs');
const HEALTH_SERVER = join(ROOT, 'src', 'mcp', 'markdownHealthServer.ts');

export type McpServerConfig = {
  /** Имя сервера. Оно же — источник тула в трейсе и в UI: [weather], [filesystem]. */
  name: string;
  command: string;
  args: string[];
  /**
   * Переменные окружения дочернего процесса. Транспорт подмешивает их к своему набору
   * (HOME, PATH, SHELL, TERM, USER), а не заменяет его, так что PATH здесь дублировать
   * не надо. Но и всё остальное из нашего .env дочернему процессу не достаётся —
   * что нужно, передаётся явно: либо здесь, либо через requiresEnv.
   */
  env?: Record<string, string>;
  enabled: boolean;
  /**
   * Имя переменной окружения, без которой сервер бессмысленен. Нет её — сервер молча
   * пропускается, а её значение уезжает дочернему процессу под тем же именем.
   * Читается в момент подключения, а не при загрузке модуля: в скриптах .env грузится
   * первым импортом, и константа успела бы взять пустоту.
   */
  requiresEnv?: string;
  /**
   * Какие тулы сервера достаются коучу. Нет поля — достаются все. Это не обёртка:
   * тулы приезжают к агенту как есть, меняется только длина списка. Смысл в том, что
   * DeepSeek выбирает тул тем хуже, чем длиннее список, а weather отдаёт одиннадцать
   * тулов, из которых коучу нужны два — остальные про наводнения и морские волны.
   */
  tools?: string[];
  /**
   * Тулы, которые пишут. Они разрешены дополнительно к tools, но появляются в списке
   * только после того, как ревьюер сказал approve и харнесс открыл гейт.
   *
   * Это та же политика, что всегда держала save_health_plan, — просто теперь она
   * распространяется и на чужие серверы. Без этого filesystem c его write_file обесценил
   * бы весь гейт: коуч положил бы неодобренный план в plans/ в обход ворот, и правило
   * «на диск не ложится ничего, пока план не одобрен» перестало бы быть правдой.
   */
  writeTools?: string[];
};

