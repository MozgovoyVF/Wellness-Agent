// Журнал обращений к базе знаний за прогон. Форма повторяет src/skills/gate.ts: объект
// создаёт харнесс на прогон, тул получает его замыканием и только пишет.
//
// Почему журнал, а не разбор newItems из SDK. В трейсе нужно видеть сам запрос и заголовки
// найденных chunks — то есть аргументы вызова и его выдачу. collectToolCalls отдаёт только
// имена тулов, и достать оттуда остальное можно лишь разбором внутренних элементов SDK
// с парсингом JSON конкретного тула. src/harness/toolCalls.ts намеренно единственное место,
// где харнесс знает про внутренности SDK, и размывать это ради одного тула не стоит.

/** Одно обращение к базе знаний: с чем пришли и что нашлось. */
export type Retrieval = {
  query: string;
  /** Заголовки найденного, по убыванию похожести. Тел chunks здесь нет — трейс не хранилище. */
  chunks: { file: string; heading: string; similarity: number }[];
};

/** Что видит тул: только запись. Читает журнал харнесс. */
export type RetrievalLog = {
  record: (entry: Retrieval) => void;
  entries: () => Retrieval[];
};

export function createRetrievalLog(): RetrievalLog {
  const log: Retrieval[] = [];

  return {
    record: (entry) => {
      log.push(entry);
    },
    // Копия, а не живой массив: результат прогона не должен ссылаться на то,
    // что кто-то ещё может дописать.
    entries: () => [...log],
  };
}
