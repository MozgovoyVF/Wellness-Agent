// Retrieval: запрос → похожие куски базы знаний. Два шага и ничего между ними.
//
// Между embed и поиском намеренно нет ничего: ни переписывания запроса, ни расширения
// синонимами. После поиска — тоже: ни reranking, ни смешивания с полнотекстовым поиском.
// Это не упущение, а граница задачи. Каждое из этих улучшений добавляет ещё один поход
// в модель и ещё одно место, где результат меняется незаметно, — а показать здесь нужно,
// как работает сам механизм.

import { embed } from './embed';
import { matchChunks, type KnowledgeMatch } from './store';

export type { KnowledgeMatch };

/** Сколько chunks отдаём по умолчанию. Пять — столько коуч успевает прочесть и учесть. */
export const DEFAULT_TOP_K = 5;

/**
 * Ищет в базе знаний куски, ближайшие к запросу по смыслу.
 *
 * Один embed запроса, один similarity search — тем же способом и той же моделью, какой
 * считались chunks при ингесте. Разойдутся модели — расстояния станут бессмысленными,
 * и поиск будет молча возвращать что попало: сравнивать векторы разных моделей нельзя.
 */
export async function searchKnowledge(
  query: string,
  topK: number = DEFAULT_TOP_K,
): Promise<KnowledgeMatch[]> {
  const [vector] = await embed([query]);
  return matchChunks(vector, topK);
}
