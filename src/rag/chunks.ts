// Разбор базы знаний на chunks. Единица знания здесь — одна `##`-секция markdown:
// у неё есть заголовок, который сам по себе несёт смысл, и тело, которое читается
// отдельно от соседей.
//
// Почему секция, а не «N символов с перекрытием»: нарезка по длине рвёт рецепт
// посередине состава, и найденный кусок оказывается бесполезен. Заголовки в knowledge/
// проставлены руками именно для того, чтобы границы chunks выбирал человек, а не счётчик.

import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

// cwd, а не import.meta.url: этот модуль зовут и скрипт из корня, и Next из .next/.
const KNOWLEDGE_DIR = join(process.cwd(), 'knowledge');

/** Кусок базы знаний: откуда взят и что в нём написано. */
export type KnowledgeChunk = {
  /** Имя файла без пути: 'recipes.md'. */
  file: string;
  /** Текст `##`-заголовка без решёток. */
  heading: string;
  /** Тело секции без заголовка. */
  content: string;
};

// Только второй уровень. `### ` под эту форму не подходит намеренно: подзаголовки
// внутри секции остаются её частью, а не становятся отдельными chunks.
const HEADING = /^##\s+(.+?)\s*$/;

/**
 * Chunks одного файла. Всё, что стоит до первого `## `, отбрасывается: это `# Заголовок`
 * файла и вводные строки — название документа, а не знание. Секция без тела тоже
 * отбрасывается: пустой chunk занял бы место в выдаче и ничего бы не сказал.
 */
function chunksOfFile(file: string, text: string): KnowledgeChunk[] {
  const chunks: KnowledgeChunk[] = [];
  let heading: string | null = null;
  let body: string[] = [];

  const flush = () => {
    if (heading === null) return;
    const content = body.join('\n').trim();
    if (content.length > 0) chunks.push({ file, heading, content });
  };

  for (const line of text.split('\n')) {
    const match = HEADING.exec(line);
    if (match === null) {
      body.push(line);
      continue;
    }
    flush();
    heading = match[1];
    body = [];
  }
  flush();

  return chunks;
}

/**
 * Вся база знаний, файл за файлом в алфавитном порядке. Порядок нужен ради
 * воспроизводимости: два ингеста подряд должны давать одинаковые id у одинаковых секций.
 */
export function readKnowledgeChunks(): KnowledgeChunk[] {
  const files = readdirSync(KNOWLEDGE_DIR)
    .filter((name) => name.endsWith('.md'))
    .sort();

  return files.flatMap((file) => chunksOfFile(file, readFileSync(join(KNOWLEDGE_DIR, file), 'utf8')));
}

/**
 * Что именно уходит в эмбеддинг: заголовок и **только первый абзац** тела.
 *
 * Не всё тело — и это измеренное решение, а не экономия. Эмбеддинг усредняет весь текст,
 * поэтому длинный хвост глушит заголовок. У рецепта хвост — список граммов («Филе лосося
 * 150 г, киноа 70 г сухой…»): семантически он почти пуст, но по объёму больше всего
 * остального. На запросе «ужин с высоким белком без молочки» это давало разгромный
 * результат — в топ-5 не попадал ни один рецепт ужина, зато выигрывали прозаические
 * правила про белок и лактозу, а «Треска с чечевицей — ужин с высоким белком, без
 * молочки» стояла тринадцатой, ниже завтраков.
 *
 * Замеры на трёх типах запросов (питание, восстановление, тренировки):
 *
 *   заголовок + всё тело      0 из 5 рецептов в топ-5, лосось 0.364
 *   только заголовок          2 из 5, лосось 0.515 — но тело не ищется вовсе
 *   заголовок + первый абзац  5 из 5, лосось 0.486 — и остальные запросы не пострадали
 *
 * В выдачу коучу при этом едет **весь** chunk: поле content хранится целиком, урезан
 * только вектор. Отсюда связь, которую легко порвать: первый абзац каждой секции обязан
 * быть сводкой, а не вступлением. В knowledge/ они так и написаны.
 */
export function embeddableText(chunk: KnowledgeChunk): string {
  return `${chunk.heading}\n\n${summaryOf(chunk.content)}`;
}

// Первый абзац — до первой пустой строки. Секция из одного абзаца отдаётся целиком.
function summaryOf(content: string): string {
  return content.split(/\n\s*\n/)[0].trim();
}
