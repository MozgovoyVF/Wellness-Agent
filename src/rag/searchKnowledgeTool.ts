// Тул поиска по базе знаний. Для агента он ничем не отличается от остальных: такой же
// вызов функции, как suggestWorkoutTemplate или read_profile с MCP-сервера.
//
// Тул локальный, хотя источник данных чужой (Postgres в Supabase), — и это осознанное
// отступление от принципа «чужой источник данных → MCP-сервер». Причины две: журнал
// retrieval через границу процесса не прокинуть, а заголовки найденного обязаны попасть
// в трейс; и сам поиск здесь не про данные человека, а про общее знание.

import { tool } from '@openai/agents';
import { z } from 'zod';
import { searchKnowledge, DEFAULT_TOP_K } from './retriever';
import type { RetrievalLog } from './retrievalLog';

/** Имя тула. Названо один раз здесь; в промпте коуча и в TOOL_LABELS оно продублировано. */
export const SEARCH_KNOWLEDGE = 'searchKnowledge';

// Что агент получает, когда база недоступна. Не ошибка: отказ инструмента не повод бросать
// работу — та же логика, что у LOCKED_MESSAGE в гейте. Ронять весь прогон из-за
// вспомогательного источника значило бы менять ценное на служебное.
const UNAVAILABLE_MESSAGE =
  'База знаний сейчас недоступна. Опирайся на профиль, дневник и любимые рецепты человека, ' +
  'а недостающее оставь общим — но ничего не выдумывай про самого человека.';

const EMPTY_MESSAGE =
  'В базе знаний ничего не нашлось по этому запросу. Попробуй переформулировать короче ' +
  'и по существу — или обойдись профилем, дневником и любимыми рецептами.';

/**
 * Фабрика тула. Журнал приходит снаружи: владеет им харнесс, а тул только пишет —
 * ровно так же, как навыки записи спрашивают гейт.
 *
 * Параметр у тула один, `query`. Размер выдачи модели не отдан намеренно: топ-K это
 * настройка поиска, а не решение агента, и лишний рычаг здесь только добавил бы способов
 * получить пустую выдачу.
 */
export function createSearchKnowledgeTool(log: RetrievalLog) {
  return tool({
    name: SEARCH_KNOWLEDGE,
    description:
      'Ищи в базе знаний рецепты, правила питания, шаблоны тренировок, правила ' +
      'восстановления. Возвращает подходящие по смыслу разделы с указанием источника. ' +
      'Вызывай до того, как писать план: рецепты и правила берут отсюда, а не из головы. ' +
      'Формулируй запрос по существу задачи и вместе с ограничениями человека — ' +
      '«ужин с высоким белком без молочки» находит нужное, «ужин» не находит.',
    parameters: z.object({
      query: z
        .string()
        .describe(
          'Что ищем, обычными словами: «ужин с высоким белком без молочки», ' +
            '«тренировка, щадящая колено», «как сдвинуть отбой раньше».',
        ),
    }),
    execute: async ({ query }) => {
      let matches;
      try {
        matches = await searchKnowledge(query, DEFAULT_TOP_K);
      } catch (error) {
        // Запись в журнал делаем и здесь: в трейсе должно быть видно, что агент ходил
        // в базу знаний и ушёл ни с чем, — иначе неудача выглядит как отсутствие попытки.
        log.record({ query, chunks: [] });
        console.log(`   поиск по базе знаний не удался: ${String(error)}`);
        return UNAVAILABLE_MESSAGE;
      }

      log.record({
        query,
        chunks: matches.map(({ file, heading, similarity }) => ({ file, heading, similarity })),
      });

      if (matches.length === 0) return EMPTY_MESSAGE;

      // Источник у каждого куска виден: без него коуч не сможет сослаться на знание
      // в плане, а ревьюер — отличить его от выдумки.
      return matches
        .map(
          (match, index) =>
            `[${index + 1}] ${match.file} → ${match.heading} (похожесть ${match.similarity})\n` +
            match.content,
        )
        .join('\n\n');
    },
  });
}
