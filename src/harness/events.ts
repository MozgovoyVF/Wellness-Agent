// Словарь событий прогона: что харнесс рассказывает о себе наружу, пока работает.
// Идиома та же, что у src/skills/gate.ts и src/rag/retrievalLog.ts: объект создаёт
// харнесс на прогон, вызывающая сторона только пишет.
//
// Зачем это вообще. Результат прогона (HealthAgentResult) отвечает на вопрос «что
// получилось», и до конца цикла его нет. Чат спрашивает другое — «что происходит
// прямо сейчас», — и ответ на это нельзя достать из возвращаемого значения по
// определению: он нужен раньше, чем значение появится.
//
// События describe только ХОД прогона. Итог остаётся возвращаемым значением: варианта
// done здесь намеренно нет, иначе один и тот же контракт описывался бы дважды и разъехался
// бы при первой правке HealthAgentResult. Роут делает `await runHealthAgent(...)` и берёт
// rounds, finalScore, toolSources, retrievals, promptVersions и durationMs оттуда.

import type { Review } from './validateReview';

/** Что случилось за прогон. Порядок вариантов — порядок, в котором они обычно приходят. */
export type AgentEvent =
  /**
   * Триаж вынес решение. blocked = true означает, что коуч не запускался вовсе:
   * раундов ноль, MCP-серверы не поднимались, на диск ничего не легло.
   */
  | { type: 'triage'; blocked: boolean; reason: string | null }
  /**
   * Раунд начался. kind различает три случая, и это не украшение: «переписывает
   * по замечаниям» и «усиливает уже одобренный» — разные вещи для того, кто смотрит,
   * а вычислить их по номеру раунда снаружи нельзя (добор идёт после approve).
   */
  | { type: 'round-start'; round: number; kind: 'first' | 'revise' | 'reinforce' }
  /**
   * Коуч позвал тул. args — сырая строка аргументов, ровно как её отдал SDK: харнесс
   * не разбирает аргументы конкретных тулов и не должен. Кому нужен запрос
   * из searchKnowledge, тот его и парсит — консоль и так тул-специфична.
   *
   * source — имя MCP-сервера, откуда тул приехал, или null у локального навыка.
   * Едет прямо в событии, а не отдельной картой: карта toolSources появляется
   * снаружи только вместе с итогом прогона, то есть через минуту после вызова,
   * и живой таймлайн до тех пор показывал бы каждый MCP-тул навыком.
   */
  | { type: 'tool'; round: number | null; name: string; args: string; source: string | null }
  /**
   * Кусок текста плана этого раунда. Это ЧЕРНОВИК: наружу уезжает finalRound —
   * последний одобренный раунд, а он не обязан быть последним. Текст, собранный
   * из дельт, показывать можно, выдавать за итоговый план нельзя.
   */
  | { type: 'plan-delta'; round: number; delta: string }
  | { type: 'review-start'; round: number }
  /** Вердикт раунда. Приходит ПОСЛЕ enforceApproveThreshold — см. runHealthAgent. */
  | { type: 'review-done'; round: number; review: Review }
  /** Закрепляющий заход: гейт открыт, коуч сохраняет. Раунда здесь нет — он вне цикла. */
  | { type: 'finalize' };

export type AgentEventHandler = (event: AgentEvent) => void;

export type Emitter = {
  send(event: AgentEvent): void;
  /**
   * Слушает ли кто-то. Читает это только streamCoach — чтобы решить, запускать заход
   * коуча стримом или обычным run(). Больше нигде ветвиться по нему не нужно и нельзя:
   * весь смысл пустого send в том, что цикл про наличие слушателя не знает.
   */
  readonly active: boolean;
};

/**
 * Эмиттер прогона. Без обработчика send — пустая функция, и поэтому в цикле нет
 * ни одного `if (onEvent)`: код читается одинаково для evals и для чата, а расхождение
 * поведения между ними невозможно по построению, а не по внимательности.
 *
 * Исключение из обработчика гасится: слушатель — это UI, и упавший рендер строки
 * таймлайна не повод ронять прогон, который стоит минуту работы и денег за ключ.
 * Та же логика, что у traceRun и у отказа базы знаний: сбой показа не сбой работы.
 */
export function createEmitter(onEvent?: AgentEventHandler): Emitter {
  if (onEvent === undefined) {
    return { send: () => {}, active: false };
  }

  return {
    send: (event) => {
      try {
        onEvent(event);
      } catch (error) {
        console.error(`Слушатель событий бросил на ${event.type}:`, error);
      }
    },
    active: true,
  };
}
