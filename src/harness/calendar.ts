// Календарь прогона: какое сегодня число и какой это день недели.
//
// Отдельный модуль, потому что это единственный факт в плане, который агентам неоткуда
// взять. Профиль и дневник приезжают тулами, прогноз — с weather-сервера, а «сегодня
// среда» не сообщает никто: тул погоды отдаёт голые ISO-даты (`2026-08-19`), задача
// пользователя говорит «на завтра», и день недели модели остаётся вывести самой.
//
// Выводит она его плохо. Не от незнания — спрошенная в лоб, модель отвечает верно, —
// а потому что делает это попутно, посреди написания прозы и при длинном контексте.
// В двух прогонах подряд ошибка была одинаковой, на день назад: 18 августа названо
// понедельником, 19-е — вторником, хотя это вторник и среда.
//
// Поэтому день недели считает код и передаёт готовым. Это та же логика, что у гейта:
// просьба в промпте «правильно считай дни недели» — просьба, а не гарантия, и провалится
// она ровно так же. Промпт может только велеть пользоваться этим блоком.

// Сколько дней показывать вперёд. Недели с запасом хватает: «план на ближайшие три дня»
// и «план на неделю» — самые длинные горизонты, которые вообще просят.
const DEFAULT_HORIZON = 8;

// Часовой пояс не задаём: берём локальное время процесса. Прибивать сюда пояс из профиля
// было бы ошибкой — локация человека живёт в data/profile.md и достаётся тулами, а этот
// модуль отвечает на вопрос «какое сегодня число», а не «где человек».
const weekday = new Intl.DateTimeFormat('ru-RU', { weekday: 'long' });
const dayMonth = new Intl.DateTimeFormat('ru-RU', { day: 'numeric', month: 'long' });

// Год дописываем сами, а не форматтером с year: 'numeric': ru-RU отдаёт «19 августа 2026 г.»,
// и точка внутри строки ломает предложение, в которое эту дату подставляют.
const fullDate = (date: Date) => `${dayMonth.format(date)} ${date.getFullYear()}`;

/** Подпись дня: «среда, 19 августа». Для сегодня и завтра — с явной пометкой. */
function line(date: Date, offset: number): string {
  const base = `${weekday.format(date)}, ${dayMonth.format(date)}`;
  if (offset === 0) return `- ${base} — сегодня`;
  if (offset === 1) return `- ${base} — завтра`;
  return `- ${base}`;
}

/**
 * Блок «Календарь» для входа агента: сегодняшняя дата и ближайшие дни с днями недели.
 *
 * Отдаётся и коучу, и ревьюеру. Ревьюеру — обязательно: он проверяет план на выдумки,
 * и без календаря не только пропустит неверный день недели, но и рискует завернуть
 * верный как выдумку — своей даты у него тоже нет.
 *
 * `now` параметром, а не `new Date()` внутри: так функция остаётся чистой, и её же можно
 * позвать с датой из трейса, когда прогон переигрывают.
 */
export function calendarBlock(now: Date = new Date(), horizon: number = DEFAULT_HORIZON): string {
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());

  const days = Array.from({ length: horizon }, (_, offset) => {
    const date = new Date(today);
    date.setDate(today.getDate() + offset);
    return line(date, offset);
  });

  return (
    `## Календарь\n` +
    `Сегодня ${weekday.format(today)}, ${fullDate(today)}.\n\n` +
    `${days.join('\n')}\n\n` +
    'Дни недели бери отсюда. Сам их не вычисляй и не выводи из дат в дневнике.'
  );
}
