// Что агент вызывал за прогон. Отдельный модуль, потому что это единственное место,
// где харнесс разбирает внутренние элементы результата SDK: держим знание о них здесь,
// а не размазываем по циклу.

import type { RunItem } from '@openai/agents';

/**
 * Имена тулов из одного захода агента, по порядку вызова. Берём только вызовы функций:
 * в newItems едут и сообщения, и результаты тулов, а нам нужен факт обращения. Повторы
 * не схлопываем — два getRecentLog подряд это и есть то, что стоит увидеть в трейсе.
 *
 * На вход берём не RunResult целиком, а нужное поле: так модуль не зависит от того,
 * какими дженериками параметризован результат конкретного агента.
 */
export function collectToolCalls(result: { newItems: RunItem[] }): string[] {
  return result.newItems.flatMap((item) =>
    item.type === 'tool_call_item' && item.rawItem.type === 'function_call'
      ? [item.rawItem.name]
      : [],
  );
}
