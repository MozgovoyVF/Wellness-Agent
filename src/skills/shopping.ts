// Навык «список покупок»: вытаскивает из плана продукты с количествами и кладёт их
// в data/shopping.md. Пишет на диск — значит, стоит за гейтом харнесса, см. index.ts.
//
// Источников два, и предпочтительный — раздел «## Список покупок», который коуч пишет сам
// (промпт требует его, когда список просили). Там продукты уже сведены и стоят по одному
// в строке в именительном падеже, поэтому разбор такого раздела почти не ошибается.
// Разбор всего плана — запасной путь для планов без раздела: он и есть та эвристика,
// которая путает падежи и склеивает «филе лосося» с «филе трески».

import { tool } from '@openai/agents';
import { z } from 'zod';
import { writeData } from './dataFiles';
import { LOCKED_MESSAGE, type Gate } from './gate';

// Количество в плане: число и единица. Порядок в альтернативе от длинных к коротким,
// иначе «кг» разберётся как «г». Отрицательный просмотр отсекает «г» внутри «грамм».
const AMOUNT = /(\d+(?:[.,]\d+)?)\s*(ст\.л\.|ч\.л\.|кг|мл|шт|г|л)(?![А-Яа-яЁё])/gu;

// Запись «2×12 кг» — это инвентарь: две гантели по двенадцать. Еду так не пишут, а под
// разбор она попадает законно, поэтому число сразу после знака умножения пропускаем.
const MULTIPLIER = /[×xх*]\s*$/u;

// Служебные слова и глаголы готовки: с них название не начинается, на них разбор имени и
// обрывается. Глаголы здесь потому, что в шагах рецепта количество стоит прямо за ними —
// «полить соком лимона 20 г», — и без обрыва глагол уезжает в название продукта.
const STOPWORDS = new Set([
  'из', 'по', 'с', 'и', 'на', 'в', 'около', 'примерно', 'до', 'или',
  'полить', 'залить', 'добавить', 'обжарить', 'варить', 'нарезать', 'посолить',
  'смешать', 'разогреть', 'взять', 'положить', 'запекать', 'держать', 'оставить',
  'подать', 'вмешать', 'сбрызнуть', 'выложить',
]);

// Заголовок раздела, который коуч пишет сам. Без учёта регистра: «## Список покупок»,
// «## Список покупок на 13–15 августа» — всё это он.
const SHOPPING_HEADING = /^##\s*Список покупок/imu;

// Пояснения в скобках. Коуч пишет в них разбивку вроде «(150 г на омлет + 150 г к треске)»,
// и количества оттуда — это то же самое количество, посчитанное второй раз, да ещё и с
// названием блюда вместо продукта. Вырезаем целиком, подставляя разделитель имени.
const PARENTHESES = /\([^)]*\)/gu;

// Не продукты. Вода в рецептах стоит с граммовкой наравне с едой, но в списке покупок ей
// делать нечего. Инвентарь попадает под тот же разбор из блока тренировки: «одной гантелью
// 12 кг» — законное «число + единица», просто не еда. Сверяем по последнему слову названия:
// оно главное («одной гантелью» → «гантелью»).
const NOT_BOUGHT = new Set([
  'вода', 'воды', 'кипяток', 'кипятка', 'лёд', 'льда',
  'гантель', 'гантели', 'гантелью', 'гантелями', 'гантелей',
  'гиря', 'гири', 'гирей', 'штанга', 'штанги', 'блин', 'блины', 'вес', 'веса', 'весом',
]);

/**
 * Название продукта — это последние слова перед количеством. Окно поиска ограничено
 * концом прошлого количества и ближайшим знаком-разделителем: без этого «гречка 80 г,
 * куриная грудка 150 г» дало бы второму продукту хвост от первого.
 */
function nameBefore(window: string): string | null {
  const segment = window.split(/[—–,:;()]/u).pop() ?? '';
  // Слово — минимум две кириллические буквы: так отсеиваются маркеры списка и хвост
  // единицы от прошлого количества, иначе «- рис» и «г рис» попадали в название.
  const words = segment.split(/[^А-Яа-яЁё-]+/u).filter((word) => /[А-Яа-яЁё]{2,}/u.test(word));

  // Двух слов хватает на всё, что человек покупает: «куриная грудка», «оливковое масло»,
  // «грецкие орехи». Третье слово почти всегда лишнее и тащит в название глагол или предлог.
  const name: string[] = [];
  for (let i = words.length - 1; i >= 0 && name.length < 2; i -= 1) {
    const word = words[i].toLowerCase();
    if (STOPWORDS.has(word)) break;
    name.unshift(word);
  }

  if (name.length === 0) return null;
  // Главное слово — последнее: по нему и решаем, еда это вообще или инвентарь.
  return NOT_BOUGHT.has(name[name.length - 1]) ? null : name.join(' ');
}

type Item = { name: string; amount: number; unit: string };

/**
 * Что именно разбирать. Есть раздел «## Список покупок» — берём только его: коуч уже свёл
 * повторы и написал продукты по одному в строке, и разбирать вдобавок весь план значило бы
 * посчитать те же граммы второй раз. Раздела нет — разбираем план целиком.
 */
function sourceText(planMarkdown: string): string {
  const heading = SHOPPING_HEADING.exec(planMarkdown);
  if (heading === null) return planMarkdown;

  const body = planMarkdown.slice(heading.index + heading[0].length);
  // Раздел кончается следующим заголовком того же уровня. Обычно он последний, но
  // полагаться на это незачем.
  const next = body.search(/^##\s/mu);
  return next === -1 ? body : body.slice(0, next);
}

/**
 * Разбор намеренно узкий, как и парсер плана в app/plan-markdown.tsx: формат задаёт
 * промпт коуча, а ревьюер требует от плана граммов и штук — значит, количества в нём
 * есть. Продукт без количества не берём: «немного орехов» в списке покупок бесполезно.
 */
function extractItems(planMarkdown: string): Item[] {
  // Разбор идёт по тексту без скобок, и все позиции считаются от него же.
  const text = sourceText(planMarkdown).replace(PARENTHESES, ';');
  const items = new Map<string, Item>();
  let cursor = 0;

  for (const match of text.matchAll(AMOUNT)) {
    const start = match.index ?? 0;
    const window = text.slice(cursor, start);
    const name = nameBefore(window);
    cursor = start + match[0].length;
    if (name === null || MULTIPLIER.test(window)) continue;

    const amount = Number(match[1].replace(',', '.'));
    const unit = match[2];
    const key = `${name}|${unit}`;
    const seen = items.get(key);

    // Один продукт может встретиться в завтраке и в ужине — количества складываем,
    // иначе в магазине не хватит ровно на второй приём пищи.
    if (seen) seen.amount += amount;
    else items.set(key, { name, amount, unit });
  }

  return [...items.values()];
}

function renderList(items: Item[]): string {
  const lines = items.map(
    (item) => `- [ ] ${item.name} — ${Number(item.amount.toFixed(2))} ${item.unit}`,
  );

  return `# Список покупок\n\nСобран из плана автоматически. Перед магазином пробегись глазами: то,\nчто в плане было без количества, сюда не попало.\n\n${lines.join('\n')}\n`;
}

/** Пишет data/shopping.md и возвращает то, что записал. */
export function generateShoppingList(planMarkdown: string): string {
  const items = extractItems(planMarkdown);
  if (items.length === 0) {
    return 'В плане не нашлось ни одного продукта с количеством — список покупок не из чего собрать. Файл не тронут.';
  }

  const list = renderList(items);
  writeData('shopping.md', list);
  return list;
}

export function createGenerateShoppingListTool(gate: Gate) {
  return tool({
    name: 'generateShoppingList',
    description:
      'Переносит список покупок из плана в отдельный файл data/shopping.md. Передавай markdown ' +
      'плана целиком — тот, что ты написал. Продукты берутся из раздела «## Список покупок», ' +
      'если он в плане есть, иначе из всего текста, но тогда разбор грубее и путает падежи — ' +
      'раздел писать надёжнее. Вызывай, когда человек просил список покупок или когда план ' +
      'на несколько дней и без закупки его не выполнить. Продукт без количества в файл ' +
      'не попадёт: класть в корзину нечего.',
    parameters: z.object({
      planMarkdown: z
        .string()
        .min(1)
        .describe('Полный markdown плана, из которого нужно собрать список покупок.'),
    }),
    execute: async ({ planMarkdown }) =>
      gate.isUnlocked() ? generateShoppingList(planMarkdown) : LOCKED_MESSAGE,
  });
}
