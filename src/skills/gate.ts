// Гейт на запись. Навыки, которые пишут на диск, спрашивают его перед каждым действием;
// открывает его харнесс — и только после того, как ревьюер поставил approve.
//
// Почему в коде, а не в промпте коуча. Промпт — это просьба, а не гарантия: модель может
// решить, что черновик стоит «сохранить на всякий случай», и неодобренный план ляжет
// в data/output.md в обход ворот. Инструкцией это не чинится — её можно не выполнить,
// а замыкание не обойти галлюцинацией. По той же причине под гейтом стоит и список
// покупок: при вердикте needs_human_professional план наружу не отдаётся, а продукты
// из него, записанные в data/shopping.md, — это тот же план, только сбоку.

/** Что видят навыки: только вопрос, ответить на который они не могут. */
export type Gate = {
  isUnlocked: () => boolean;
};

/** Что видит харнесс: тот же гейт плюс единственный способ его открыть. */
export type GateControl = Gate & {
  unlock: () => void;
};

/** Ответ модели на попытку записи до одобрения. Не ошибка: агент должен продолжить работу. */
export const LOCKED_MESSAGE =
  'Записать не могу: план ещё не одобрен ревьюером. Сохранение выполняется после одобрения ' +
  'и запрашивается отдельно — сейчас просто закончи работу над планом и верни его текстом.';

export function createGate(): GateControl {
  let unlocked = false;

  return {
    isUnlocked: () => unlocked,
    unlock: () => {
      unlocked = true;
    },
  };
}
