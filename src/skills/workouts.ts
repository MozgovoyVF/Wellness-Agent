// Навык «шаблон тренировки». Ничего не читает с диска: это заготовки, зашитые в код.
// Смысл навыка не в данных, а в конкретности — шаблон приходит с подходами, повторами и
// минутами, поэтому коуч не может отдать «кардио 20–40 минут», которое ревьюер завернёт.

import { tool } from '@openai/agents';
import { z } from 'zod';

// Все четыре щадят колено: глубоких приседаний с весом, выпадов и бега здесь нет нигде.
// Шаблон — не готовый план: коуч подгоняет его под профиль и дневник, а не отдаёт как есть.
const TEMPLATES = {
  upper_body: `Верх тела, 50 минут
1. Разминка: эллипс 6 минут, лёгкий темп.
2. Жим гантелей лёжа — 4 подхода по 10 повторов.
3. Тяга верхнего блока к груди — 4 подхода по 12 повторов.
4. Жим гантелей сидя вверх — 3 подхода по 12 повторов.
5. Тяга гантели в наклоне, каждой рукой — 3 подхода по 12 повторов.
6. Планка — 3 подхода по 45 секунд, отдых 60 секунд.`,

  lower_body_low_impact: `Низ тела без нагрузки на колено, 45 минут
1. Разминка: велотренажёр 8 минут, сопротивление низкое.
2. Жим ногами в неполной амплитуде (сгиб не глубже 90°) — 4 подхода по 12 повторов.
3. Румынская тяга с гантелями — 3 подхода по 12 повторов.
4. Сгибания ног в тренажёре — 3 подхода по 15 повторов.
5. Подъёмы на носки стоя — 3 подхода по 20 повторов.
6. Ягодичный мостик — 3 подхода по 15 повторов.`,

  cardio_low_impact: `Кардио без ударной нагрузки, 35 минут
1. Велотренажёр 10 минут, пульс спокойный, разговор даётся легко.
2. Эллипс 15 минут: чередуй 2 минуты быстрее и 2 минуты спокойно.
3. Велотренажёр 10 минут на снижение, к концу пульс возвращается к спокойному.
Бега по асфальту и прыжков в этом шаблоне нет намеренно.`,

  home_dumbbells: `Дома с гантелями 2×12 кг и ковриком, 30 минут
1. Разминка: суставная гимнастика 4 минуты.
2. Жим гантелей лёжа на коврике — 3 подхода по 12 повторов.
3. Тяга двух гантелей в наклоне — 3 подхода по 12 повторов.
4. Румынская тяга с гантелями — 3 подхода по 15 повторов.
5. Жим гантелей вверх сидя — 3 подхода по 12 повторов.
6. Планка — 3 подхода по 40 секунд.`,
} as const;

export type WorkoutGoal = keyof typeof TEMPLATES;

export function suggestWorkoutTemplate(goal: WorkoutGoal): string {
  return TEMPLATES[goal];
}

export const suggestWorkoutTemplateTool = tool({
  name: 'suggestWorkoutTemplate',
  description:
    'Возвращает готовый шаблон тренировки с упражнениями, подходами, повторами и минутами. ' +
    'Все шаблоны уже щадят правое колено. Вызывай, когда в плане есть тренировка: шаблон ' +
    'даёт ту конкретность, без которой пункт «сходи в зал» бесполезен. Подгони его под ' +
    'профиль и дневник — если человек тренировал верх вчера, шаблон верха сегодня не бери.',
  parameters: z.object({
    goal: z
      .enum(['upper_body', 'lower_body_low_impact', 'cardio_low_impact', 'home_dumbbells'])
      .describe(
        'Какой шаблон нужен: upper_body — верх тела в зале; lower_body_low_impact — низ тела ' +
          'без нагрузки на колено; cardio_low_impact — кардио без ударной нагрузки; ' +
          'home_dumbbells — дома с гантелями, когда до зала не дойти.',
      ),
  }),
  execute: async ({ goal }) => suggestWorkoutTemplate(goal),
});
