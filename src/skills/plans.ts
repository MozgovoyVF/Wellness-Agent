// Навык «сохранить план»: пишет план в data/output.md. Обёртки tool() здесь больше нет —
// модели этот тул показывает MCP-сервер (save_health_plan).
//
// Функция сама по себе гейта не знает и знать не должна: она чистая запись. Держит гейт
// харнесс — теперь фильтром тулов (см. src/mcp/connectServers.ts), потому что сервер живёт
// в отдельном процессе и замыкание туда не дотянется. Ту же функцию харнесс зовёт
// напрямую как страховку, когда коуч сохранил не тот текст (см. runHealthAgent).

import { readData, writeData } from './dataFiles';

/** Перезаписывает data/output.md. Возвращает то, что агент увидит как результат вызова. */
export function savePlan(markdown: string): string {
  writeData('output.md', markdown);
  return 'ok: план записан в data/output.md.';
}

/**
 * Лежит ли в data/output.md ровно этот план. Сравниваем по тексту, а не по факту вызова
 * тула: модель зовёт save_health_plan охотно, а вот текст передаёт своими словами —
 * короче, приглаженный, без куска.
 *
 * Спрашивают отсюда двое, и по разным поводам, но правило одно. Харнесс — чтобы понять,
 * донёс ли коуч текст в закрепляющем заходе, и дописать самому, если нет. Роут
 * /api/plan/notion — чтобы решить, можно ли отправить присланный план наружу: файл
 * пишется только после approve, поэтому совпадение с ним и есть доказательство, что план
 * одобрен. Гейт роуту не годится — он живёт ровно столько, сколько прогон, а кнопку
 * человек жмёт после.
 *
 * Расхождение в хвостовых пробелах не считается: это не потеря содержимого.
 */
export function planMatchesDisk(markdown: string): boolean {
  try {
    return readData('output.md').trim() === markdown.trim();
  } catch {
    // Файла нет — значит, и совпадать не с чем.
    return false;
  }
}
