// Навык «предпочтения»: чистые функции над data/preferences.md.
//
// Это вторая долгая память рядом с профилем, и разница между ними важна. Профиль
// человек написал про себя сам; предпочтения копит система из того, что он подтвердил
// по ходу дела («запомни», «понравилось»). Поэтому пишет сюда только харнесс: тул
// update_preferences существует на сервере, но коучу не даётся никогда — долгая память
// не должна пополняться решением модели.
//
// Файл плоский: одна запись — одна строка. Группировка по дням потребовала бы разбора
// заголовков ради файла, который читается хвостом.

import { readData, writeData } from './dataFiles';

const ENTRY_PREFIX = '- ';

/** Последние `entries` записей. Хвост, а не файл целиком: он растёт, а место в контексте конечно. */
export function getPreferences(entries: number): string {
  const lines = readData('preferences.md')
    .split('\n')
    .filter((line) => line.startsWith(ENTRY_PREFIX));

  if (lines.length === 0) return 'Подтверждённых предпочтений пока нет.';
  // entries <= 0 — это «не показывай ничего», а не «покажи всё»: slice(-0) в JS равен
  // slice(0) и вернул бы файл целиком. Ошибка тихая, поэтому проверка явная.
  if (entries <= 0) return 'Подтверждённых предпочтений пока нет.';
  return lines.slice(-entries).join('\n');
}

/**
 * Дописывает запись в конец. Дописывает, а не перезаписывает: это история подтверждений,
 * и затереть её одной неудачной записью нельзя. Формат строки задаёт вызывающий —
 * угадывать за него дату и модуль этой функции нечем.
 */
export function appendPreference(entry: string): string {
  const text = readData('preferences.md').trimEnd();
  writeData('preferences.md', `${text}\n${entry.trim()}\n`);
  return 'ok: предпочтение записано в data/preferences.md.';
}
