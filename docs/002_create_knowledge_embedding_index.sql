-- 002 · Векторный индекс по knowledge_chunks.embedding.
--
-- ВЫПОЛНЯТЬ ПОСЛЕ ПЕРВОГО `npm run ingest`, а не сразу за 001.
--
-- ─── Сначала прочти, нужен ли он вообще ──────────────────────────────────────
--
-- На 67 строках этот индекс не нужен и даже вреден. ivfflat — приближённый поиск:
-- он делит векторы на `lists` кластеров и при запросе смотрит только ближайшие
-- (по умолчанию `ivfflat.probes = 1`, то есть ровно один кластер). При lists = 4
-- это примерно 17 строк из 67 — то есть настоящий топ-5 он может и не увидеть.
-- Полный перебор на таком размере точный и мгновенный, и планировщик выберет его сам.
--
-- Поэтому: пока база знаний меньше нескольких тысяч секций, этот файл можно
-- не выполнять вовсе — retrieval работает и без него. Он здесь ради того, чтобы
-- было видно, как индекс заводится, и чтобы его не пришлось искать, когда база вырастет.
--
-- ─── Если всё-таки создаёшь ──────────────────────────────────────────────────
--
-- Оператор vector_cosine_ops обязан совпадать с тем, которым retriever сортирует
-- выдачу в src/rag/store.ts (`<=>`). Разойдутся — индекс просто не будет
-- использоваться, и поиск молча уедет в полный перебор.
--
-- При росте базы поднимай lists примерно до корня из числа строк и перестраивай
-- индекс (drop index, затем этот же create).

-- Сборка ivfflat берёт выборку фиксированного размера, а не по числу строк: около
-- 10 000 векторов по 1536 чисел — это ~59 МБ, независимо от того, что в таблице
-- их 67. На Supabase maintenance_work_mem по умолчанию 32 МБ, и без этой строки
-- create index падает с «memory required is 59 MB, maintenance_work_mem is 32 MB».
-- SET действует на сессию, поэтому выполнять его надо вместе с create index,
-- одним запуском в SQL Editor.
set maintenance_work_mem = '128MB';

create index if not exists knowledge_chunks_embedding_idx
  on knowledge_chunks using ivfflat (embedding vector_cosine_ops) with (lists = 4);
